// Saves the IRSA observation lists for the five challenge targets (all six
// detectors) into lib/target-snapshots.mjs. api/archive.js serves these only
// when the live IRSA search is down; images are always fetched live.
//
//   node scripts/snapshot-targets.mjs
//
// Run it while IRSA's search is up, then commit lib/target-snapshots.mjs.
// A target whose query fails keeps its previously saved list.
import {writeFile} from 'node:fs/promises';
import {queryCollection, normalizeRecords} from '../lib/archive.mjs';
import {targets} from '../dist/targets.mjs';
import previous from '../lib/target-snapshots.mjs';

const out = {savedAt: new Date().toISOString(), targets: structuredClone(previous.targets || {})};
let updated = 0, kept = 0;

for (const [key, t] of Object.entries(targets)) {
  const results = await Promise.allSettled(['spherex_dr1', 'spherex_qr3'].map(c => queryCollection({ra: t.ra, dec: t.dec}, c)));
  const ok = results.filter(r => r.status === 'fulfilled');
  if (ok.length < results.length) {
    console.warn(`${t.name}: IRSA search failed (${results.find(r => r.status === 'rejected').reason.message}); keeping the saved list.`);
    kept++; continue;
  }
  const rows = ok.flatMap(r => r.value.rows), retrievedAt = new Date().toISOString();
  const detectors = {};
  for (let d = 1; d <= 6; d++) {
    const records = normalizeRecords(rows, d);
    if (records.length) detectors[d] = {retrievedAt, source: ok.map(r => r.value.source), records};
  }
  out.targets[key] = {name: t.name, ra: t.ra, dec: t.dec, detectors};
  console.log(`${t.name}: ${Object.entries(detectors).map(([d, v]) => `D${d} ${v.records.length}`).join(', ') || 'no coverage'}`);
  updated++;
}

if (!updated) { console.error('\nIRSA search is unavailable; lib/target-snapshots.mjs left unchanged.'); process.exit(1); }
const header = '// Generated by scripts/snapshot-targets.mjs. Saved IRSA observation lists for the\n// challenge targets, used by api/archive.js only when the IRSA search is down.\n';
await writeFile(new URL('../lib/target-snapshots.mjs', import.meta.url), `${header}export default ${JSON.stringify(out)};\n`);
console.log(`\n${updated} target(s) refreshed, ${kept} kept from the previous snapshot.`);
